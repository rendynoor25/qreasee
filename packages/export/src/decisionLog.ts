/** EX-05: Decision log as Markdown and CSV (immutable DecisionRecords). */

import type { DocState, IndicatorResult } from "@qreasee/shared";

export function decisionLogMarkdown(state: DocState): string {
  const lines: string[] = ["# Decision log", ""];
  if (state.records.length === 0) {
    lines.push("_No decisions recorded yet._");
    return lines.join("\n");
  }
  for (const r of state.records) {
    const decision = state.decisions.find((d) => d.id === r.decisionId);
    lines.push(`## ${decision?.title ?? "Decision"}`);
    if (decision?.question) lines.push(`**Question.** ${decision.question}`);
    lines.push("");
    lines.push(`**Chosen.** ${r.rationale}`);
    lines.push(`**By.** ${r.by}`);
    lines.push(`**At.** ${new Date(r.at).toISOString()}`);
    if (r.rejected.length > 0) {
      lines.push("");
      lines.push("**Rejected options.**");
      for (const rej of r.rejected) {
        lines.push(`- ${rej.name}`);
      }
    }
    lines.push("");
    lines.push("**Rules snapshot.** KDB max " + (r.rulesSnapshot.kdbMax ?? "—") + ", KLB max " + (r.rulesSnapshot.klbMax ?? "—"));
    lines.push("");
  }
  return lines.join("\n");
}

export function decisionLogCsv(state: DocState): string {
  const header = "decision,question,chosen_branch,rationale,by,at,rejected";
  const rows = state.records.map((r) => {
    const d = state.decisions.find((x) => x.id === r.decisionId);
    return [
      csv(d?.title ?? ""),
      csv(d?.question ?? ""),
      csv(r.rejected.map((x) => x.name).join(" | ")),
      csv(r.rationale),
      csv(r.by),
      new Date(r.at).toISOString(),
      csv(r.rejected.map((x) => x.name).join(" | ")),
    ].join(",");
  });
  return [header, ...rows].join("\n");
}

function csv(value: string): string {
  if (/[",\n]/.test(value)) return `"${value.replace(/"/g, '""')}"`;
  return value;
}

export interface ComparisonBranch {
  name: string;
  color: string;
  plan: { outer: { x: number; y: number }[]; holes: { x: number; y: number }[][] }[];
  indicators: IndicatorResult[];
}

/** EX-04: an SVG comparison sheet the app rasterises to PNG. */
export function comparisonSheetSvg(
  title: string,
  branches: ComparisonBranch[],
  bestByKey: Record<string, string | undefined>,
): string {
  const colW = 240;
  const thumbH = 200;
  const width = Math.max(640, branches.length * colW + 40);
  const height = 470;
  const parts: string[] = [];
  parts.push(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">`,
    `<rect width="${width}" height="${height}" fill="#0b0d10"/>`,
    `<text x="20" y="36" fill="#e8ebef" font-family="sans-serif" font-size="20" font-weight="700">${escapeXml(title)}</text>`,
    `<text x="20" y="58" fill="#9aa4b2" font-family="sans-serif" font-size="12">Comparison sheet · generated by Qreasee</text>`,
  );

  branches.forEach((b, i) => {
    const x = 20 + i * colW;
    parts.push(
      `<rect x="${x}" y="76" width="${colW - 16}" height="${thumbH}" rx="8" fill="#12151a" stroke="${b.color}"/>`,
    );
    parts.push(drawPlan(b.plan, x + 8, 84, colW - 32, thumbH - 16, b.color));
    parts.push(
      `<text x="${x + 10}" y="${76 + thumbH + 22}" fill="${b.color}" font-family="sans-serif" font-size="14" font-weight="600">${escapeXml(b.name)}</text>`,
    );
  });

  const rowY = 76 + thumbH + 40;
  const keys = collectKeys(branches);
  keys.forEach((key, row) => {
    const y = rowY + row * 22;
    parts.push(
      `<text x="20" y="${y}" fill="#9aa4b2" font-family="sans-serif" font-size="12">${escapeXml(key)}</text>`,
    );
    branches.forEach((b, i) => {
      const r = b.indicators.find((x) => x.key === key);
      const text = r ? indicatorText(r) : "—";
      const isBest = bestByKey[key] === b.name;
      const color = isBest ? "#22c55e" : "#e8ebef";
      parts.push(
        `<text x="${24 + i * colW}" y="${y}" fill="${color}" font-family="sans-serif" font-size="12" font-weight="${isBest ? 700 : 400}">${escapeXml(text)}</text>`,
      );
    });
  });

  parts.push("</svg>");
  return parts.join("");
}

function collectKeys(branches: ComparisonBranch[]): string[] {
  const keys: string[] = [];
  for (const b of branches) {
    for (const r of b.indicators) if (!keys.includes(r.key)) keys.push(r.key);
  }
  return keys;
}

function indicatorText(r: IndicatorResult): string {
  if (r.range) return `${trim(r.range.low)}–${trim(r.range.high)} ${r.unit ?? ""}`.trim();
  if (r.value === undefined) return r.status;
  return `${trim(r.value)} ${r.unit ?? ""}`.trim();
}

function trim(n: number): string {
  return Math.round(n * 100) / 100 + "";
}

function drawPlan(
  plan: { outer: { x: number; y: number }[]; holes: { x: number; y: number }[][] }[],
  x: number,
  y: number,
  w: number,
  h: number,
  color: string,
): string {
  const pts = plan.flatMap((p) => p.outer);
  if (pts.length === 0) {
    return `<text x="${x + w / 2}" y="${y + h / 2}" fill="#4a5563" font-family="sans-serif" font-size="12" text-anchor="middle">empty</text>`;
  }
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  for (const p of pts) {
    minX = Math.min(minX, p.x);
    minY = Math.min(minY, p.y);
    maxX = Math.max(maxX, p.x);
    maxY = Math.max(maxY, p.y);
  }
  const scale = Math.min(w / (maxX - minX || 1), h / (maxY - minY || 1)) * 0.9;
  const ox = x + w / 2 - ((minX + maxX) / 2) * scale;
  const oy = y + h / 2 + ((minY + maxY) / 2) * scale;
  const path = (ring: { x: number; y: number }[]) =>
    ring
      .map((p, i) => `${i === 0 ? "M" : "L"}${(ox + p.x * scale).toFixed(1)},${(oy - p.y * scale).toFixed(1)}`)
      .join(" ") + " Z";
  const d = plan
    .map((p) => path(p.outer) + p.holes.map((hole) => " " + path(hole)).join(" "))
    .join(" ");
  return `<path d="${d}" fill="${color}33" stroke="${color}" stroke-width="1.5" fill-rule="evenodd"/>`;
}

function escapeXml(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}
