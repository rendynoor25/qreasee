export function t(
  lang: Lang,
  key: I18nKey,
  vars?: Record<string, string | number>,
): string {
  const raw = (lang === "id" ? id[key] : undefined) ?? en[key] ?? key;
  if (!vars) return raw;
  return Object.entries(vars).reduce(
    (acc, [k, v]) => acc.replace(new RegExp(`\\{${k}\\}`, "g"), String(v)),
    raw,
  );
}

export function makeTranslator(lang: Lang) {
  return (key: I18nKey, vars?: Record<string, string | number>) =>
    t(lang, key, vars);
}

export type Translator = (key: I18nKey, vars?: Record<string, string | number>) => string;

